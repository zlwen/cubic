import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(fileURLToPath(new URL('.', import.meta.url)), '..');
const require = createRequire(import.meta.url);
const { chapterOneLevels } = require(resolve(root, 'dist-tests/src/levels/tutorialLevels.js'));
const { findSolution } = require(resolve(root, 'dist-tests/src/game/solver.js'));

const solutions = chapterOneLevels.map((level, index) => {
  const result = findSolution(level, 2_000_000);
  if (!result.solution) {
    throw new Error(`Could not solve stage ${index + 1}; visited ${result.visitedStates} states.`);
  }
  console.log(`Stage ${String(index + 1).padStart(2, '0')}: ${result.solution.length} actions`);
  return result.solution;
});

const output = `// Generated by tools/generate-bloxorz-solutions.mjs. Do not edit by hand.
import type { PuzzleAction } from '../game/index';

export const bloxorzSolutions: readonly (readonly PuzzleAction[])[] = ${JSON.stringify(solutions, null, 2)};
`;

const targets = [
  resolve(root, 'src/levels/bloxorzSolutions.ts'),
  resolve(root, 'assets/scripts/shared/levels/bloxorzSolutions.ts'),
];

for (const target of targets) writeFileSync(target, output);
