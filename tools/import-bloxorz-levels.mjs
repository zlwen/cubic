import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(fileURLToPath(new URL('.', import.meta.url)), '..');
const sourcePath = resolve(root, 'third_party/bloxorz_gba/levels.json');
const source = JSON.parse(readFileSync(sourcePath, 'utf8'));

if (!Array.isArray(source.levels) || source.levels.length !== 33) {
  throw new Error('Expected exactly 33 levels in the pinned Bloxorz.gba data.');
}

for (const [index, level] of source.levels.entries()) {
  if (!Array.isArray(level.tiles) || level.tiles.length !== 10
    || level.tiles.some((row) => typeof row !== 'string' || row.length !== 15)) {
    throw new Error(`Stage ${index + 1} must contain a 15 x 10 tile grid.`);
  }
}

const output = `// Generated by tools/import-bloxorz-levels.mjs. Do not edit by hand.
// Source: bloxorz_gba game/levels.json @ 8d552f867c06caa8bc9953eefa13ecb2bb9d8edf (MIT).

export type RawBloxorzSwitchMode = 'on' | 'off' | 'onoff';
export type RawBloxorzSwitchAction = readonly [number, number, RawBloxorzSwitchMode];

export interface RawBloxorzLevel {
  readonly id: string;
  readonly code: number;
  readonly tiles: readonly string[];
  readonly spawn: readonly [number, number];
  readonly switches?: Readonly<Record<string, readonly RawBloxorzSwitchAction[]>>;
  readonly splits?: Readonly<Record<string, readonly [number, number, number, number]>>;
}

export const bloxorzLevelData: readonly RawBloxorzLevel[] = ${JSON.stringify(source.levels, null, 2)};
`;

const targets = [
  resolve(root, 'src/levels/bloxorzLevelData.ts'),
  resolve(root, 'assets/scripts/shared/levels/bloxorzLevelData.ts'),
];

for (const target of targets) writeFileSync(target, output);
